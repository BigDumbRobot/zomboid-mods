#!/usr/bin/env python3
# Writes media/clothing/clothingItems/Whisp_FaceMask.xml: the mask model cut
# from the vanilla face (tools/mask.py), with every vanilla skin as a texture
# choice. The order must match S.MaskSkins in Whisperers_Stake.lua (zombie
# skins first, male then female, then human skins); a mask picks its index
# with item:getVisual():setTextureChoice(). The tester's gear checks compare them.
#   python3 tools/gen_face_mask_xml.py
import os
here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, '..', 'Contents/mods/TheWhisperers/42/media/clothing/clothingItems/Whisp_FaceMask.xml')
human = {'male': ['MaleBody0%d%s' % (i, s) for i in range(1, 6) for s in ('', 'a')],
         'female': ['FemaleBody0%d' % i for i in range(1, 6)]}
zombie = {}
for g, p in (('male', 'M'), ('female', 'F')):
    zombie[g] = []
    for i in range(1, 5):
        zombie[g].append('%s_ZedBody0%d' % (p, i))
        zombie[g] += ['%s_ZedBody0%d_level%d' % (p, i, l) for l in range(1, 4)]
skins = zombie['male'] + zombie['female'] + human['male'] + human['female']
lines = ['<?xml version="1.0" encoding="utf-8"?>', '<clothingItem>',
         '\t<!-- The face cut from the body mesh, worn over the wearer\'s face. Its UVs are the',
         '\t     body\'s, so each texture choice is a vanilla skin, stretched and mutilated',
         '\t     (tools/mask_textures.py): a mask shows the face it was cut from',
         '\t     (Whisperers_Stake.lua, S.MaskSkins). Generated by tools/gen_face_mask_xml.py;',
         '\t     the model by tools/mask.py. -->',
         '\t<m_GUID>27544c70-4efa-4eb5-8cfe-6b6757cbf5eb</m_GUID>',
         '\t<m_MaleModel>skinned\\clothes\\Whisp_FaceMask_M</m_MaleModel>',
         '\t<m_FemaleModel>skinned\\clothes\\Whisp_FaceMask_F</m_FemaleModel>',
         '\t<m_AltMaleModel></m_AltMaleModel>', '\t<m_AltFemaleModel></m_AltFemaleModel>',
         '\t<m_Static>false</m_Static>', '\t<m_AllowRandomHue>false</m_AllowRandomHue>',
         '\t<m_AllowRandomTint>false</m_AllowRandomTint>', '\t<m_AttachBone></m_AttachBone>',
         '\t<m_HatCategory>nobeard</m_HatCategory>']
lines += ['\t<textureChoices>WhispMask\\%s</textureChoices>' % s for s in skins]
lines += ['</clothingItem>', '']
open(out, 'w').write('\n'.join(lines))
print('wrote', len(skins), 'texture choices to', os.path.normpath(out))
